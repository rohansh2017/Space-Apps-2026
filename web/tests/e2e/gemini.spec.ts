import { expect, test } from '@playwright/test'
import { expandPanels } from './hud'

// Calls the real Worker route (Gemini). Needs a deployment with the GEMINI_API_KEY secret: `make e2e-live`.
test.skip(!process.env.GEMINI_TEST, 'needs the deployed Worker with the Gemini secret (make e2e-live)')

test('F21 live: the demo sentence fills the panel with schema-valid values', async ({ page }) => {
  test.slow()
  await page.goto('/')
  await expandPanels(page)
  await expect(page.getByTestId('view')).toContainText('Plan:')
  await page.getByPlaceholder(/survive 4 days of dark/).fill('survive 4 days of dark, talk to Earth half the time')
  await page.getByRole('button', { name: 'Interpret with Gemini' }).click()
  const suggestion = page.getByTestId('suggestion')
  const quota = page.getByText(/Gemini answered 429/)
  await expect(suggestion.or(quota)).toBeVisible({ timeout: 45_000 })
  // 429 is Google's quota for our key, not a defect: the app reported it in place and kept working, which is what it must do
  test.skip(await quota.isVisible(), 'Gemini quota exhausted (429); the in-place error was shown')
  await expect(suggestion).toContainText('Max continuous darkness: 96 hours')
  await expect(suggestion).toContainText('Min Earth visibility: 50 %')
  await expect(page.getByTestId('suggestion-rejected')).toHaveCount(0)
  await page.getByRole('button', { name: 'Apply to the panel' }).click()
  await expect(page.getByLabel('Max continuous darkness')).toHaveValue('96')
  await expect(page.getByLabel('Min Earth visibility')).toHaveValue('50')
})

test('F22 live: Gemini describes the horizon, or the template stands in', async ({ page }) => {
  test.slow()
  await page.goto('/')
  await expandPanels(page)
  await expect(page.getByTestId('view')).toContainText('Plan:')
  await page.getByRole('button', { name: 'Describe with Gemini' }).click()
  await expect(page.getByTestId('horizon-note')).not.toContainText('Template sentence', { timeout: 45_000 })
  const note = (await page.getByTestId('horizon-note').textContent())!
  const text = (await page.getByTestId('horizon-sentence').textContent())!
  console.log(`GEMINI describe: ${note} :: ${text}`)
  expect(text.length).toBeGreaterThan(40) // a sentence is always shown: Gemini's, or the engine's template
  // 429 is Google's quota for our key, not a defect: the template stood in and said why
  test.skip(/answered 429/.test(note), 'Gemini quota exhausted (429); the template stood in')
  expect(note).toMatch(/Generated by Gemini|not in the facts/) // either outcome is correct behaviour; any other error is not
})
