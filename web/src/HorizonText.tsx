import { useState } from 'react'
import type { HorizonFacts } from './describe'
import { askDescription, looksLikeDescription, numbersCheck, templateDescription } from './describe'

/** F22: one short description of the panorama. Template by default; Gemini on request, kept only if every number is a fact. */
export default function HorizonText({ facts }: { facts: HorizonFacts }) {
  const [stored, setStored] = useState<{ key: string; text: string; note: string } | null>(null)
  const [busy, setBusy] = useState(false)
  const key = JSON.stringify(facts)
  const generated = stored?.key === key ? stored : null // a sentence written for other facts no longer applies
  const setGenerated = (g: { text: string; note: string }) => setStored({ key, ...g })
  const describe = async () => {
    setBusy(true)
    try {
      const text = await askDescription(facts)
      setGenerated(!looksLikeDescription(text)
        ? { text: templateDescription(facts), note: 'Gemini did not describe the horizon, so the template is shown.' }
        : numbersCheck(text, facts)
          ? { text, note: 'Generated by Gemini from engine facts; every number checked.' }
          : { text: templateDescription(facts), note: 'Gemini\'s text contained a number that is not in the facts, so the template is shown.' })
    } catch (e) {
      setGenerated({ text: templateDescription(facts), note: `${e instanceof Error ? e.message : String(e)}; template shown.` })
    } finally {
      setBusy(false)
    }
  }
  return (
    <div className="horizon-text" data-testid="horizon-text">
      <p data-testid="horizon-sentence">{generated ? generated.text : templateDescription(facts)}</p>
      <p className="note">
        <span data-testid="horizon-note">{generated ? generated.note : 'Template sentence from engine facts.'}</span>{' '}
        <button type="button" disabled={busy} onClick={describe}>{busy ? 'Asking Gemini…' : 'Describe with Gemini'}</button>
      </p>
    </div>
  )
}
